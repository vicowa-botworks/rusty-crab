//! The provider wire types, ported from picoclaw `pkg/providers/protocoltypes`.
//!
//! These structs are what providers receive and what session files contain, so
//! their JSON is a stored format, not an internal detail. The contract that makes
//! them hard is that they mix `omitempty` with bare fields, which means **absent,
//! `null`, `[]` and `""` are four different encodings** and each comes from a
//! different Go value:
//!
//! | Go value | Wire |
//! |---|---|
//! | `Message{}` | `{"role":"","content":""}` -- everything else dropped |
//! | `LLMResponse{}` | `…,"reasoning_details":null}` -- no `omitempty`, always emitted |
//! | `LLMResponse{ReasoningDetails: []T{}}` | `…,"reasoning_details":[]}` |
//! | `ToolFunctionDefinition{}` | `…,"parameters":null}` |
//! | `ToolFunctionDefinition{Parameters: map…{}}` | `…,"parameters":{}}` |
//!
//! A port that collapses any two of these still produces JSON a provider accepts.
//! What it breaks is the next release reading back a session file, which is a
//! failure with no request to attach it to.
//!
//! Three more things the fixtures pin, each invisible until a byte moves:
//!
//! * **Field order is declaration order.** Not alphabetical, not insertion order.
//! * [`StreamChunk`] has no `json` tags at all, so its keys are the Go field names
//!   with their original capitalisation.
//! * Fields tagged `json:"-"` never appear. [`ToolCall::name`] and
//!   [`ToolCall::arguments`] sit directly beside [`FunctionCall::name`] and
//!   [`FunctionCall::arguments`], which *are* on the wire -- a port that maps by
//!   field name rather than by tag leaks internal state into provider requests.
//!
//! Conformance: `../../conformance`, replayed in `tests/conformance.rs` against
//! fixtures generated by the Go code itself.

pub mod go_time;

use crab_gojson::{omit, GoMarshal, ObjectWriter, Value};
pub use go_time::format_rfc3339_nano;

/// Re-exported because public signatures mention it; the encoder itself lives in
