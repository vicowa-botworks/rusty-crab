/// Encodes `value` exactly as `json.Marshal` would, at the top level.
///
/// Discards everything written before a failure, because Go returns no bytes at
/// all when any part of the value is unencodable.
pub fn marshal<T: GoMarshal + ?Sized>(value: &T) -> Result<Vec<u8>, crab_gojson::MarshalError> {
    let mut out = Vec::new();
    value.marshal_go(&mut out)?;
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn json<T: GoMarshal + ?Sized>(v: &T) -> String {
        String::from_utf8(marshal(v).expect("encodable")).expect("UTF-8")
    }

    /// The four ways to be absent, on three different fields. This is the
    /// distinction the whole crate exists to keep: a provider accepts all four,
    /// and only a session file can tell them apart afterwards.
    #[test]
    fn absent_null_empty_and_empty_string_are_four_documents() {
        assert_eq!(json(&Message::default()), r#"{"role":"","content":""}"#);
        // No omitempty, and a slice: nil is null.
        assert_eq!(
            json(&LLMResponse::default()),
            r#"{"content":"","finish_reason":"","reasoning":"","reasoning_details":null}"#
        );
        // Same field, empty instead of nil: a different document.
        let empty = LLMResponse {
            reasoning_details: Some(vec![]),
            ..LLMResponse::default()
        };
        assert!(json(&empty).ends_with(r#""reasoning_details":[]}"#));
        // No omitempty, and a map: nil is null, empty is {}.
        assert!(json(&ToolFunctionDefinition::default()).ends_with(r#""parameters":null}"#));
        let params = ToolFunctionDefinition {
            parameters: Some(BTreeMap::<String, crab_gojson::Value>::new()),
            ..ToolFunctionDefinition::default()
        };
        assert!(json(&params).ends_with(r#""parameters":{}}"#));
    }

    /// `json:"-"` is per field, and here a hidden field sits beside a visible one
    /// with the *same name*: `ToolCall.ThoughtSignature` is internal while
    /// `FunctionCall.ThoughtSignature` goes to the provider. A port that maps by
    /// name gets one of the two backwards, and the one it gets wrong is either a
    /// leak or a dropped reasoning signature.
    #[test]
    fn hidden_fields_are_not_emitted_even_beside_their_visible_twins() {
        let call = ToolCall {
            id: "c1".into(),
            name: "HIDDEN_NAME".into(),
            arguments: Some(BTreeMap::<String, crab_gojson::Value>::new()),
            thought_signature: "HIDDEN_SIG".into(),
            function: Some(FunctionCall {
                name: "visible".into(),
                arguments: "{}".into(),
                thought_signature: "ON_THE_WIRE".into(),
            }),
            ..ToolCall::default()
        };
        let expected = concat!(
            r#"{"id":"c1","function":{"name":"visible","arguments":"{}","#,
            r#""thought_signature":"ON_THE_WIRE"}}"#,
        );
        assert_eq!(json(&call), expected);
    }

    /// Keys follow the struct, not the alphabet: `role` before `content` before
    /// `model_name`, even though `attachments` and `content` would sort the other
    /// way. Sorting is what a Go *map* gets, and `parameters` is sorted -- which
    /// is why both orders appear in one document.
    #[test]
    fn struct_keys_follow_declaration_and_map_keys_sort() {
        let mut params: BTreeMap<String, crab_gojson::Value> = BTreeMap::new();
        params.insert("z".into(), crab_gojson::Value::Int(1));
        params.insert("A".into(), crab_gojson::Value::Int(2));
        let msg = Message {
            role: "user".into(),
            model_name: "m".into(),
            media: Some(vec!["x".into()]),
            ..Message::default()
        };
        assert_eq!(
            json(&msg),
            r#"{"role":"user","content":"","model_name":"m","media":["x"]}"#
        );
        let def = ToolDefinition {
            def_type: "function".into(),
            function: ToolFunctionDefinition {
                name: "f".into(),
                description: String::new(),
                parameters: Some(params),
            },
            ..ToolDefinition::default()
        };
        assert_eq!(
            json(&def),
            r#"{"type":"function","function":{"name":"f","description":"","parameters":{"A":2,"z":1}}}"#
        );
    }

    /// Go's `json.Marshal` returns no bytes at all when any part fails, so a
    /// non-finite float anywhere in a parameters map fails the enclosing value --
    /// it does not skip the field and carry on.
    #[test]
    fn one_unencodable_float_fails_the_whole_document() {
        let mut params: BTreeMap<String, crab_gojson::Value> = BTreeMap::new();
        params.insert("fine".into(), crab_gojson::Value::Str("yes".into()));
        params.insert("bad".into(), crab_gojson::Value::Float(f64::NAN));
        let msg = Message {
            role: "user".into(),
            tool_calls: Some(vec![ToolCall {
                arguments: Some(params.clone()),
                ..ToolCall::default()
            }]),
            ..Message::default()
        };
        // arguments is json:"-", so it is never visited and cannot fail. The
        // visible path that can fail is a tool definition's parameters.
        assert!(marshal(&msg).is_ok());
        let def = ToolDefinition {
            def_type: "function".into(),
            function: ToolFunctionDefinition {
                parameters: Some(params),

                ..ToolFunctionDefinition::default()
            },
            ..ToolDefinition::default()
        };
        let err = marshal(&def).expect_err("NaN is unencodable");
        assert_eq!(err.to_string(), "json: unsupported value: NaN");
    }
}
