pub use crab_gojson as go_json;

use std::collections::BTreeMap;

/// An instant as Go's `time.Time` holds it, in a fixed-offset zone.
///
/// `nanos` is the sub-second part in `[0, 1e9)` -- Go's `Time.Nanosecond()` -- and
/// the zone is an offset in seconds rather than a name, because `MarshalJSON`
/// writes the offset and never the name, and a name would need a tz database to
/// resolve.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct GoTime {
    pub unix_seconds: i64,
    pub nanos: u32,
    pub offset_seconds: i32,
}

impl GoTime {
    /// What `MarshalJSON` returns: the quoted RFC3339Nano string.
    pub fn to_json_string(&self) -> String {
        format!(
            "\"{}\"",
            format_rfc3339_nano(self.unix_seconds, self.nanos, self.offset_seconds)
        )
    }
}

impl GoMarshal for GoTime {
    fn marshal_go(&self, out: &mut Vec<u8>) -> Result<(), crab_gojson::MarshalError> {
        out.extend_from_slice(self.to_json_string().as_bytes());
        Ok(())
    }
}

#[derive(Debug, Clone, Default, PartialEq)]
pub struct ToolCall {
    /// `json:"id"` -- no `omitempty`, so an empty call still emits `"id":""`.
    pub id: String,
    pub call_type: String,
    /// A pointer: `omitempty` here means nil only, so a pointer to an empty
    /// [`FunctionCall`] is still emitted.
    pub function: Option<FunctionCall>,
    /// `json:"-"` -- internal, and easily leaked: [`FunctionCall::name`] is on the
    /// wire and this is not.
    pub name: String,
    /// `json:"-"` -- parsed arguments, for the runtime's use only.
    pub arguments: Option<BTreeMap<String, Value>>,
    /// `json:"-"`.
    pub thought_signature: String,
    pub extra_content: Option<ExtraContent>,
}

impl GoMarshal for ToolCall {
    fn marshal_go(&self, out: &mut Vec<u8>) -> Result<(), crab_gojson::MarshalError> {
        let mut o = ObjectWriter::new(out);
        o.field("id", &self.id)?;
        if !omit::str(&self.call_type) {
            o.field("type", &self.call_type)?;
        }
        if !omit::pointer(&self.function) {
            o.field("function", self.function.as_ref().unwrap())?;
        }
        // name, arguments and thought_signature are json:"-": never written.
        if !omit::pointer(&self.extra_content) {
            o.field("extra_content", self.extra_content.as_ref().unwrap())?;
        }
        o.finish();
        Ok(())
    }
}

