//! Token-count estimation, ported from `pkg/tokenizer/estimator.go` in
//! vicowa-botworks/picoclaw.
//!
//! This is an *estimator*, not a tokenizer: nothing here consults a real BPE
//! vocabulary. It exists to decide when a conversation has to be compacted, so
//! its value to the running system is its monotonic relationship to real token
//! cost -- and its value to existing users is that it is **the same number the Go
//! code produces**, because a different number moves the compaction point and
//! silently changes which turns survive.
//!
//! That constraint is what makes the port non-obvious. Three things in the
//! original are invisible from a distance and are pinned by conformance fixtures
//! rather than by review:
//!
//! * `content` and `reasoning_content` are counted in **runes**, while every
//!   tool-call field and `tool_call_id` is counted in **bytes**. The Go source
//!   mixes `utf8.RuneCountInString` and `len` in one expression list; picking
//!   either rule uniformly is wrong, and wrong in the direction that changes
//!   when compaction fires for every non-Latin conversation.
//! * The scale is `chars * 2 / 5` -- a multiply then a truncating divide, i.e.
//!   floor. Not `chars / 2.5`, not round.
//! * Media adds a flat 256 **after** scaling, so folding it into `chars`
//!   multiplies it by 0.4.
//!
//! The tool-definition seam goes further: it measures `len(json.Marshal(x))`, so
//! it depends on Go's encoder -- key ordering, HTML escaping, float formatting --
//! and contributes nothing at all for a value Go refuses to encode. See
//! [`go_json`].
//!
//! Conformance: `../../conformance`, replayed in `tests/conformance.rs` against
//! fixtures generated by the Go code itself.

pub mod go_json;

use serde::Deserialize;

/// Per structured system block: an allowance for the JSON envelope
/// (`type`, `text`, `cache_control`) around the text.
const PER_PART_OVERHEAD: usize = 20;

/// Per message: role label, JSON structure, separators.
const MESSAGE_OVERHEAD: usize = 12;

/// Per media item. Deliberately not run through the character scale -- actual
/// cost depends on resolution and on how each provider tokenizes images, so this
/// is a flat guess added at the end.
const MEDIA_TOKENS_PER_ITEM: usize = 256;

/// Per tool definition: `type` field, JSON structure, separators.
const TOOL_DEF_OVERHEAD: usize = 20;

#[derive(Debug, Clone, Default, PartialEq, Deserialize)]
pub struct ContentBlock {
    /// `"text"` in practice; the estimator ignores it.
    #[serde(rename = "type", default)]
    pub part_type: String,
    #[serde(default)]
    pub text: String,
}

#[derive(Debug, Clone, Default, PartialEq, Deserialize)]
pub struct FunctionCall {
    #[serde(default)]
    pub name: String,
    #[serde(default)]
    pub arguments: String,
}

#[derive(Debug, Clone, Default, PartialEq, Deserialize)]
pub struct ToolCall {
    #[serde(default)]
    pub id: String,
    #[serde(rename = "type", default)]
    pub call_type: String,
    /// Absent when the call came from a format that puts the name at the top
    /// level instead. `name` is then the fallback -- see
    /// [`estimate_message_tokens`].
    #[serde(default)]
    pub function: Option<FunctionCall>,
    /// Mirrors `function.name` when a function is present, and is the only name
    /// when it is not. Not part of the provider wire format (`json:"-"` in Go),
    /// which is exactly why it is easy to omit from a port.
    #[serde(default)]
    pub name: String,
}

#[derive(Debug, Clone, Default, PartialEq, Deserialize)]
pub struct Message {
    #[serde(default)]
    pub role: String,
    #[serde(default)]
    pub content: String,
    #[serde(default)]
    pub reasoning_content: String,
    #[serde(default)]
    pub system_parts: Vec<ContentBlock>,
    #[serde(default)]
    pub tool_calls: Vec<ToolCall>,
    #[serde(default)]
    pub tool_call_id: String,
    /// Attachments are counted, never inspected: the estimator charges a flat
    /// per-item cost because real cost is resolution- and provider-dependent.
    #[serde(default)]
    pub media: Vec<String>,
}

#[derive(Debug, Clone, Default, PartialEq, Deserialize)]
pub struct ToolFunctionDefinition {
    #[serde(default)]
    pub name: String,
    #[serde(default)]
    pub description: String,
    /// `None` is Go's nil map, which the original distinguishes from an empty
    /// map: a nil map is skipped, an empty one contributes `"{}"`.
    #[serde(default)]
    pub parameters: Option<go_json::Value>,
}

#[derive(Debug, Clone, Default, PartialEq, Deserialize)]
pub struct ToolDefinition {
    #[serde(rename = "type", default)]
    pub def_type: String,
    #[serde(default)]
    pub function: ToolFunctionDefinition,
}

/// Estimates the token cost of one message.
///
/// Ported from `EstimateMessageTokens`. The character tally is built from
/// deliberately different units, and the order matters:
///
/// 1. `content`, or the system-parts tally if that is larger -- **max, not sum**.
///    `system_parts` is an alternative rendering of the same text for
///    cache-aware adapters, so counting both would double it.
/// 2. plus `reasoning_content` (runes), the tool-call fields (bytes) and
///    `tool_call_id` (bytes).
/// 3. plus [`MESSAGE_OVERHEAD`], then scaled by `* 2 / 5`.
/// 4. plus [`MEDIA_TOKENS_PER_ITEM`] per media item, outside the scale.
pub fn estimate_message_tokens(msg: &Message) -> usize {
    let content_chars = msg.content.chars().count();

    let mut system_parts_chars = 0usize;
    if !msg.system_parts.is_empty() {
        for part in &msg.system_parts {
            system_parts_chars += part.text.chars().count();
        }
        system_parts_chars += msg.system_parts.len() * PER_PART_OVERHEAD;
    }

    let mut chars = content_chars.max(system_parts_chars);
    chars += msg.reasoning_content.chars().count();

    for tc in &msg.tool_calls {
        // Bytes, not runes: these are `len()` in the original.
        chars += tc.id.len() + tc.call_type.len();
        match &tc.function {
            // The wire format for most providers. `tc.name` mirrors
            // `function.name`, so counting both would double it.
            Some(f) => chars += f.name.len() + f.arguments.len(),
            // Some formats carry a top-level name with no function.
            None => chars += tc.name.len(),
        }
    }

    if !msg.tool_call_id.is_empty() {
        chars += msg.tool_call_id.len();
    }

    chars += MESSAGE_OVERHEAD;

    let mut tokens = chars * 2 / 5;
    tokens += msg.media.len() * MEDIA_TOKENS_PER_ITEM;
    tokens
}

/// Estimates the token cost of the tool definitions attached to a request.
///
/// Ported from `EstimateToolDefsTokens`. `parameters` contributes the byte
/// length of its Go-JSON encoding, and a value that Go cannot encode contributes
/// **nothing** -- the original checks `json.Marshal`'s error and skips the whole
/// map rather than encoding the fields that happened to be fine. A `None`
/// (Go's nil map) is skipped for a different reason and lands on the same
/// number.
pub fn estimate_tool_defs_tokens(defs: &[ToolDefinition]) -> usize {
    if defs.is_empty() {
        return 0;
    }

    let mut total_chars = 0usize;
    for d in defs {
        total_chars += d.function.name.len() + d.function.description.len();

        if let Some(params) = &d.function.parameters {
            if let Ok(len) = go_json::encoded_len(params) {
                total_chars += len;
            }
        }

        total_chars += TOOL_DEF_OVERHEAD;
    }

    total_chars * 2 / 5
}

#[cfg(test)]
mod tests {
    use super::*;

    fn message() -> Message {
        Message {
            role: "user".into(),
            ..Default::default()
        }
    }

    #[test]
    fn empty_message_still_charges_the_envelope() {
        // 12 bytes of overhead * 2 / 5 = 4.
        assert_eq!(estimate_message_tokens(&message()), 4);
    }

    #[test]
    fn content_is_runes_and_tool_ids_are_bytes() {
        // One rune of CJK is three bytes: a byte-counting port would report 6.
        let mut m = message();
        m.content = "行".into();
        assert_eq!(estimate_message_tokens(&m), (1 + 12) * 2 / 5);

        let mut m = message();
        m.tool_calls = vec![ToolCall {
            id: "行".into(),
            function: Some(FunctionCall {
                name: String::new(),
                arguments: String::new(),
            }),
            ..Default::default()
        }];
        assert_eq!(estimate_message_tokens(&m), (3 + 12) * 2 / 5);
    }

    #[test]
    fn system_parts_replace_content_rather_than_adding_to_it() {
        let mut m = message();
        m.content = "aaaaaaaaaa".into();
        m.system_parts = vec![ContentBlock {
            part_type: "text".into(),
            text: "bb".into(),
        }];
        // max(10, 2 + 20) = 22, not 32.
        assert_eq!(estimate_message_tokens(&m), (22 + 12) * 2 / 5);
    }

    #[test]
    fn media_is_added_after_scaling() {
        let mut m = message();
        m.content = "hello".into();
        m.media = vec!["a.png".into(), "b.png".into()];
        assert_eq!(estimate_message_tokens(&m), (5 + 12) * 2 / 5 + 512);
    }

    #[test]
    fn tool_call_without_function_falls_back_to_the_top_level_name() {
        let mut m = message();
        m.tool_calls = vec![ToolCall {
            id: "id".into(),
            call_type: "function".into(),
            function: None,
            name: "lookup".into(),
        }];
        assert_eq!(estimate_message_tokens(&m), (2 + 8 + 6 + 12) * 2 / 5);
    }

    #[test]
    fn scaling_truncates() {
        // 14 * 2 / 5 = 5.6 -> 5. A port that rounds, or that divides by 2.5 in
        // floating point, reports 6 here.
        let mut m = message();
        m.content = "ab".into();
        assert_eq!(estimate_message_tokens(&m), 5);
        m.content = "abc".into();
        assert_eq!(estimate_message_tokens(&m), 6);
    }

    #[test]
    fn absent_parameters_cost_nothing_but_empty_ones_cost_two_bytes() {
        // Go's `Parameters != nil` guard skips a nil map entirely; an empty but
        // non-nil map still encodes as "{}".
        let with = |params: Option<go_json::Value>| ToolDefinition {
            function: ToolFunctionDefinition {
                name: "tool".into(),
                description: "desc".into(),
                parameters: params,
            },
            ..Default::default()
        };
        // 4 + 4 + 20 = 28 -> 11
        assert_eq!(estimate_tool_defs_tokens(&[with(None)]), 11);
        // 4 + 4 + 2 + 20 = 30 -> 12
        assert_eq!(
            estimate_tool_defs_tokens(&[with(Some(go_json::Value::Object(Default::default())))]),
            12
        );
        assert_eq!(estimate_tool_defs_tokens(&[]), 0);
    }

    #[test]
    fn unencodable_parameters_contribute_nothing() {
        let def = |params: go_json::Value| ToolDefinition {
            function: ToolFunctionDefinition {
                name: "tool".into(),
                description: "desc".into(),
                parameters: Some(params),
            },
            ..Default::default()
        };
        let mut m = std::collections::BTreeMap::new();
        m.insert("k".to_string(), go_json::Value::Float(f64::NAN));
        // Same total as the nil case: the failed encode adds zero, it does not
        // add the bytes it would have produced for the fields that were fine.
        assert_eq!(
            estimate_tool_defs_tokens(&[def(go_json::Value::Object(m))]),
            estimate_tool_defs_tokens(&[ToolDefinition {
                function: ToolFunctionDefinition {
                    name: "tool".into(),
                    description: "desc".into(),
                    parameters: None,
                },
                ..Default::default()
            }])
        );
    }
}
